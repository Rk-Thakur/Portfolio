// Generates supabase/seed.sql from lib/data.ts, so the database starts with
// exactly what the live site shows.  Run:  npm run db:seed-sql
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// --- Load lib/data.ts (transpile TS -> JS in a temp dir, then import) -------
const src = readFileSync(join(root, 'lib/data.ts'), 'utf8');
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 } }).outputText;
const tmp = mkdtempSync(join(tmpdir(), 'seed-'));
const file = join(tmp, 'data.mjs');
writeFileSync(file, js);
const data = await import(pathToFileURL(file).href);
rmSync(tmp, { recursive: true, force: true });

// --- Hero / About copy now lives on the profile object ---
const copy = data.profile;

// --- SQL helpers -------------------------------------------------------------
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a && a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const MONTHS = { Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6, Jul: 7, Aug: 8, Sep: 9, Oct: 10, Nov: 11, Dec: 12 };
const toDate = (label) => {
  const t = label.trim();
  if (/present/i.test(t)) return null;
  const [mon, year] = t.split(/\s+/);
  if (!MONTHS[mon] || !/^\d{4}$/.test(year)) throw new Error(`Cannot parse date "${label}"`);
  return `${year}-${String(MONTHS[mon]).padStart(2, '0')}-01`;
};
const splitRange = (range) => range.split(/\s+[—–-]\s+/);

// --- Build SQL ----------------------------------------------------------------
const { profile: p, stats, strengths, skills, experience, projects, education, marquee } = data;
const out = [];
out.push(`-- Generated by scripts/generate-seed.mjs from lib/data.ts. Do not edit by hand.
-- Safe to re-run: replaces all portfolio content (keeps contact messages and admins).
begin;

truncate public.experience_projects, public.skills, public.skill_groups, public.stats,
         public.strengths, public.experiences, public.projects, public.education, public.profile
  restart identity cascade;
`);

out.push(`insert into public.profile (id, name, short_name, initials, title, email, phone, phone_href, location,
  github_url, github_handle, linkedin_url, linkedin_handle, availability, hero_headline, hero_tagline, hero_intro,
  about_heading, about_intro, roles, about_tags, marquee)
values (1, ${q(p.name)}, ${q(p.short)}, ${q(p.initials)}, ${q(p.title)}, ${q(p.email)}, ${q(p.phone)}, ${q(p.phoneHref)}, ${q(p.location)},
  ${q(p.github)}, ${q(p.githubHandle)}, ${q(p.linkedin)}, ${q(p.linkedinHandle)}, ${q(copy.availability)}, ${q(copy.heroHeadline)},
  ${q(copy.heroTagline)}, ${q(copy.heroIntro)}, ${q(copy.aboutHeading)}, ${q(copy.aboutIntro)},
  ${arr(p.roles)}, ${arr(copy.aboutTags)}, ${arr(marquee)});
`);

out.push('insert into public.stats (value, suffix, label, decimals, position) values');
out.push(stats.map((s, i) => `  (${s.value}, ${q(s.suffix)}, ${q(s.label)}, ${s.decimals ?? 0}, ${i})`).join(',\n') + ';\n');

out.push('insert into public.strengths (area, body, position) values');
out.push(strengths.map((s, i) => `  (${q(s.area)}, ${q(s.text)}, ${i})`).join(',\n') + ';\n');

out.push('insert into public.skill_groups (title, icon, position) values');
out.push(skills.map((g, i) => `  (${q(g.title)}, ${q(g.icon)}, ${i})`).join(',\n') + ';\n');
for (const g of skills) {
  out.push(`insert into public.skills (group_id, name, position)
select g.id, s.name, s.ord - 1 from public.skill_groups g,
  unnest(${arr(g.items)}) with ordinality as s(name, ord)
where g.title = ${q(g.title)};`);
}
out.push('');

out.push('insert into public.projects (slug, title, badge, icon, category, summary, highlights, tags, app_store_url, play_store_url, position) values');
out.push(projects.map((pr, i) =>
  `  (${q(pr.slug)}, ${q(pr.title)}, ${q(pr.badge)}, ${q(pr.icon)}, ${q(pr.cat)}, ${q(pr.summary)},\n   ${arr(pr.highlights)},\n   ${arr(pr.tags)}, ${q(pr.appStore)}, ${q(pr.playStore)}, ${i})`
).join(',\n') + ';\n');

out.push('insert into public.experiences (role, company, subtitle, start_date, end_date, location, points, tags, independent, position) values');
out.push(experience.map((e, i) => {
  const [from, to] = splitRange(e.date);
  const end = toDate(to);
  return `  (${q(e.role)}, ${q(e.company)}, ${q(e.sub)}, ${q(toDate(from))}, ${end ? q(end) : 'null'}, ${q(e.location)},\n   ${arr(e.points)},\n   ${arr(e.tags)}, ${e.independent ? 'true' : 'false'}, ${i})`;
}).join(',\n') + ';\n');

for (const e of experience) {
  if (!e.projects?.length) continue;
  out.push(`insert into public.experience_projects (experience_id, project_id, position)
select e.id, pr.id, s.ord - 1
from public.experiences e
cross join unnest(${arr(e.projects)}) with ordinality as s(slug, ord)
join public.projects pr on pr.slug = s.slug
where e.company = ${q(e.company)} and e.role = ${q(e.role)};`);
}
out.push('');

out.push('insert into public.education (date_label, degree, school, location, position) values');
out.push(education.map((ed, i) => `  (${q(ed.date)}, ${q(ed.degree)}, ${q(ed.school)}, ${q(ed.loc)}, ${i})`).join(',\n') + ';\n');

out.push('commit;\n');

const target = join(root, 'supabase/seed.sql');
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target}`);
console.log(`  ${projects.length} projects, ${experience.length} experiences, ${skills.length} skill groups (${skills.reduce((n, g) => n + g.items.length, 0)} skills), ${education.length} education, ${stats.length} stats, ${strengths.length} strengths`);
